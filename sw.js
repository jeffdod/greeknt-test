var SLOW_MS = 5000;

self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CORE).then(function (c) {
    return Promise.all(CORE_FILES.map(function (u) {
      return fetch(new Request(u, { cache: 'reload' })).then(function (r) { if (r.ok) return c.put(u, r); }).catch(function () {});
    }));
  }).then(function () { return self.skipWaiting(); }));
});

self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf('gnt-core-') === 0 && k !== CORE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

function isStatic(url) { return /\.(webp|woff2?|png|jpe?g|ico|svg)$/i.test(url.pathname); }

function networkFirst(req) {
  return new Promise(function (resolve) {
    var done = false;
    function fromCache() {
      return caches.match(req, { ignoreSearch: true }).then(function (m) {
        if (m) return m;
        if (req.mode === 'navigate') return caches.match('./index.html');
        return undefined;
      });
    }
    var timer = setTimeout(function () {
      fromCache().then(function (m) { if (m && !done) { done = true; resolve(m); } });
    }, SLOW_MS);
    /* 'no-cache' asks the server whether the file has changed, instead of trusting the browser's own copy, which a host can keep for ten minutes */
    fetch(req, { cache: 'no-cache' }).then(function (res) {
      clearTimeout(timer);
      if (res && res.ok) { var copy = res.clone(); caches.open(CORE).then(function (c) { c.put(req, copy); }); }
      if (!done) { done = true; resolve(res); }
    }).catch(function () {
      clearTimeout(timer);
      if (done) return;
      fromCache().then(function (m) { done = true; resolve(m || Response.error()); });
    });
  });
}

function cacheFirst(req, url) {
  return caches.match(req).then(function (m) {
    if (m) return m;
    return fetch(req).then(function (res) {
      if (res && res.ok && res.status === 200) {
        var copy = res.clone();
        caches.open(url.pathname.indexOf('/images/pdf-pages/') >= 0 ? IMAGES : CORE).then(function (c) { c.put(req, copy); });
      }
      return res;
    });
  });
}

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;     /* other sites (such as the visit counter) are left alone */
  if (req.headers.has('range')) return;
  e.respondWith(isStatic(url) ? cacheFirst(req, url) : networkFirst(req));
});
